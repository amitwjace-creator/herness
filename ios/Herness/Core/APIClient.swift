import Foundation

enum HTTPMethod: String { case get = "GET", post = "POST" }

enum APIError: Error, LocalizedError, Equatable {
    case invalidEndpoint(String)
    case invalidPairingKey
    case invalidInput(String)
    case unauthorized
    case http(status: Int, message: String)
    case invalidResponse
    case decoding
    case transport

    var errorDescription: String? {
        switch self {
        case .invalidEndpoint(let message), .invalidInput(let message): return message
        case .invalidPairingKey: return "Enter the 43-character pairing key generated by your Herness mobile server."
        case .unauthorized: return "The server rejected this pairing key. Reconnect with a current key."
        case .http(_, let message): return message
        case .invalidResponse: return "The server returned an unexpected response. Check that this is a Herness mobile API endpoint."
        case .decoding: return "The server response could not be read. Update the app and Herness server to compatible versions."
        case .transport: return "Cannot reach the server. Check the server address, network connection, and HTTPS certificate."
        }
    }
}

/// Authorization never follows a redirect to another endpoint.
final class NoRedirectDelegate: NSObject, URLSessionTaskDelegate {
    func urlSession(_ session: URLSession, task: URLSessionTask,
                    willPerformHTTPRedirection response: HTTPURLResponse,
                    newRequest request: URLRequest,
                    completionHandler: @escaping (URLRequest?) -> Void) {
        completionHandler(nil)
    }
}

final class APIClient {
    let baseURL: URL
    private let pairingKey: String
    private let session: URLSession
    private let redirectDelegate: NoRedirectDelegate

    static func validatedBaseURL(_ raw: String) throws -> URL {
        let value = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !value.isEmpty, value.utf8.count <= 2048,
              !value.contains("\\"), !value.unicodeScalars.contains(where: { CharacterSet.whitespacesAndNewlines.contains($0) || CharacterSet.controlCharacters.contains($0) }),
              var parts = URLComponents(string: value),
              let scheme = parts.scheme?.lowercased(), let host = parts.host?.lowercased(), !host.isEmpty,
              parts.user == nil, parts.password == nil, parts.query == nil, parts.fragment == nil,
              parts.percentEncodedPath.isEmpty || parts.percentEncodedPath == "/",
              parts.port == nil || (1...65535).contains(parts.port ?? 0) else {
            throw APIError.invalidEndpoint("Enter a server origin such as https://herness.example.com, without a path, credentials, or query.")
        }
        var secure = scheme == "https"
        #if DEBUG
        secure = secure || (scheme == "http" && ["localhost", "127.0.0.1", "::1", "[::1]"].contains(host))
        #endif
        guard secure else { throw APIError.invalidEndpoint("The server address must use HTTPS with a trusted certificate.") }
        parts.scheme = scheme
        parts.host = host
        parts.path = ""
        if scheme == "https" && parts.port == 443 { parts.port = nil }
        if scheme == "http" && parts.port == 80 { parts.port = nil }
        guard let url = parts.url else { throw APIError.invalidEndpoint("Enter a valid server address.") }
        return url
    }

    init(baseURL: URL, pairingKey: String, configuration: URLSessionConfiguration = .ephemeral) throws {
        self.baseURL = try Self.validatedBaseURL(baseURL.absoluteString)
        guard pairingKey.utf8.count == 43,
              pairingKey.unicodeScalars.allSatisfy({
                  (65...90).contains($0.value) || (97...122).contains($0.value) ||
                  (48...57).contains($0.value) || $0.value == 45 || $0.value == 95
              }) else {
            throw APIError.invalidPairingKey
        }
        self.pairingKey = pairingKey
        let config = configuration.copy() as! URLSessionConfiguration
        config.urlCache = nil
        config.requestCachePolicy = .reloadIgnoringLocalCacheData
        config.httpCookieStorage = nil
        config.httpShouldSetCookies = false
        config.urlCredentialStorage = nil
        config.timeoutIntervalForRequest = 30
        config.timeoutIntervalForResource = 90
        config.waitsForConnectivity = false
        self.redirectDelegate = NoRedirectDelegate()
        self.session = URLSession(configuration: config, delegate: redirectDelegate, delegateQueue: nil)
    }

    deinit { session.invalidateAndCancel() }

    func cancelRequests() {
        session.getAllTasks { tasks in tasks.forEach { $0.cancel() } }
    }

    func request<T: Decodable>(_ path: String, method: HTTPMethod = .get,
                               body: JSONValue? = nil, query: [URLQueryItem] = []) async throws -> T {
        // Callers supply fixed API paths. No absolute or encoded traversal paths.
        guard path.hasPrefix("/api/"), !path.contains(".."), !path.contains("%"),
              !path.contains("?"), !path.contains("#"), !path.contains("\\"),
              var components = URLComponents(url: baseURL, resolvingAgainstBaseURL: false) else {
            throw APIError.invalidEndpoint("Invalid API path.")
        }
        components.path = path
        components.queryItems = query.isEmpty ? nil : query
        guard let url = components.url else { throw APIError.invalidEndpoint("Invalid API address.") }
        var request = URLRequest(url: url)
        request.httpMethod = method.rawValue
        request.setValue("Bearer " + pairingKey, forHTTPHeaderField: "Authorization")
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        request.setValue("no-store", forHTTPHeaderField: "Cache-Control")
        if method == .post {
            request.setValue("application/json", forHTTPHeaderField: "Content-Type")
            request.httpBody = try JSONEncoder().encode(body ?? .object([:]))
        }
        let data: Data
        let response: URLResponse
        do {
            (data, response) = try await session.data(for: request)
        } catch is CancellationError { throw CancellationError() }
        catch let error as URLError where error.code == .cancelled { throw CancellationError() }
        catch { throw APIError.transport }
        try Task.checkCancellation()
        guard let http = response as? HTTPURLResponse else { throw APIError.invalidResponse }
        if http.statusCode == 401 || http.statusCode == 403 { throw APIError.unauthorized }
        guard (200..<300).contains(http.statusCode) else {
            let json = try? JSONDecoder().decode(JSONValue.self, from: data)
            let detail = json?["error"]?.stringValue ?? "Server request failed (HTTP \(http.statusCode))."
            let scrubbed = String(detail.replacingOccurrences(of: pairingKey, with: "[redacted]").prefix(2000))
            throw APIError.http(status: http.statusCode, message: scrubbed)
        }
        guard data.count <= 32_000_000,
              http.mimeType == "application/json" || http.mimeType?.hasSuffix("+json") == true else {
            throw APIError.invalidResponse
        }
        do { return try JSONDecoder().decode(T.self, from: data) }
        catch { throw APIError.decoding }
    }
}
